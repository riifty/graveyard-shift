def clamp(x): return max(0.0, min(1.0, x))

rng = random.Random(666)
presets = [("INIT - Neutral", [.15, .15, 0, .1, 0, .4, .1, .5, .5])]
for cat, (base, items) in CATS.items():
    for item in items:
        name, tag = item.split("|")
        p = dict(base)
        for k, d in TAGS[tag].items():
            p[k] = 0 if (k == "crush" and d == -1) else p[k] + d
        v = [clamp(p[k] + rng.uniform(-.06, .06)) for k in KEYS]
        presets.append((f"{cat} - {name}", [round(x, 2) for x in v]))

out = ["// AUTO-GENERATED by tools/make_presets.py  -  edit that script, not this file.",
       "#pragma once", "namespace GSPresets {",
       "struct Preset { const char* name; float v[9]; };",
       'inline const char* const paramIds[9] = { ' + ", ".join(f'"{k}"' for k in KEYS) + ' };',
       "inline const Preset all[] = {"]
for n, v in presets:
    out.append(f'    {{ "{n}", {{ ' + ", ".join(f"{float(x)}f" for x in v) + " } },")
out += ["};", "inline const int count = (int) (sizeof (all) / sizeof (all[0]));", "}"]
pathlib.Path(__file__).resolve().parent.parent.joinpath("Source", "Presets.h").write_text("\n".join(out) + "\n")
print(len(presets), "presets written")
